#!/usr/bin/env bash
# =============================================================================
# Riddle's Notebook — One-Time Setup
# =============================================================================
# This script helps you configure the default AI API key so that
# all users of your app get AI-powered responses without any setup.
#
# You only need to run this ONCE before building the APK.
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

CONFIG_FILE="app/default_api_key.properties"

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

echo ""
echo -e "${GREEN}${BOLD}╔══════════════════════════════════════════════════════╗${NC}"
echo -e "${GREEN}${BOLD}║       Riddle's Notebook — One-Time Setup            ║${NC}"
echo -e "${GREEN}${BOLD}╚══════════════════════════════════════════════════════╝${NC}"
echo ""
echo -e "This will configure the FREE AI that powers your app."
echo -e "Users won't need to do anything — it just works."
echo ""

# ── Step 1: Get Groq API Key ────────────────────────────────────

echo -e "${YELLOW}${BOLD}Step 1: Get a FREE Groq API Key${NC}"
echo ""
echo -e "  Go to: ${CYAN}https://console.groq.com/keys${NC}"
echo "  - Sign up with your email (or Google/GitHub login)"
echo "  - No credit card required"
echo "  - Click 'Create API Key', give it a name, and copy it"
echo "  - The key looks like: gsk_xxxxxxxxxxxxxxxxxxxxxx"
echo ""

# Try to open browser
if command -v xdg-open &>/dev/null; then
    xdg-open "https://console.groq.com/keys" 2>/dev/null || true
elif command -v open &>/dev/null; then
    open "https://console.groq.com/keys" 2>/dev/null || true
fi

# ── Step 2: Enter the key ───────────────────────────────────────

read -r -p "Paste your Groq API key here: " API_KEY

if [[ -z "$API_KEY" ]]; then
    echo ""
    echo -e "${YELLOW}⚠ No key entered. You can run ./setup.sh again later.${NC}"
    echo -e "The app will still work, but users will need to enter their own API keys."
    exit 0
fi

# Basic validation
if [[ ! "$API_KEY" =~ ^gsk_ ]]; then
    echo ""
    echo -e "${YELLOW}⚠ That doesn't look like a Groq API key (should start with 'gsk_').${NC}"
    echo -e "If you're sure it's correct, we'll use it anyway."
    read -r -p "Continue? [Y/n] " CONFIRM
    if [[ "$CONFIRM" =~ ^[Nn] ]]; then
        echo "Setup cancelled."
        exit 0
    fi
fi

# ── Step 3: Save to config ──────────────────────────────────────

cat > "$CONFIG_FILE" << EOF
# Riddle's Notebook — Default AI Configuration
# Auto-generated by setup.sh
# Your Groq API key (free tier — no credit card needed)

groq_api_key=$API_KEY
EOF

echo ""
echo -e "${GREEN}${BOLD}╔══════════════════════════════════════════════════════╗${NC}"
echo -e "${GREEN}${BOLD}║  ✓ Setup complete!                                  ║${NC}"
echo -e "${GREEN}${BOLD}╚══════════════════════════════════════════════════════╝${NC}"
echo ""
echo -e "  API key saved to: ${CYAN}$CONFIG_FILE${NC}"
echo ""
echo -e "  Next step: ${BOLD}./build.sh${NC}"
echo -e "  This will build the APK with AI pre-configured."
echo ""
echo -e "  Your users will install the app and AI works instantly!"
echo ""
